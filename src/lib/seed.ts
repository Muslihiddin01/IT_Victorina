// Заполняем базу первыми темами и вопросами, если она пустая
export async function seedIfEmpty(db: Db) {
  const [{ count }] = await db.query<{ count: number }>("SELECT count(*)::int AS count FROM topics");
  if (count > 0) return;

  for (const [index, topic] of SEED_TOPICS.entries()) {
    const [row] = await db.query<{ id: number }>(
      "INSERT INTO topics (title, position) VALUES ($1, $2::int) RETURNING id",
      [topic.title, index + 1],
    );
    for (const [text, options] of topic.questions) {
      await db.query(
        "INSERT INTO questions (topic_id, text, options, correct) VALUES ($1::int, $2, $3::text::jsonb, 0)",
        [row.id, text, JSON.stringify(options)],
      );
    }
  }
}

// Админ берётся из переменных окружения ADMIN_LOGIN и ADMIN_PASSWORD.
// Поменяешь пароль в настройках Vercel — после перезапуска он обновится здесь.
export async function syncAdmin(db: Db) {
  const login = process.env.ADMIN_LOGIN?.trim().toLowerCase();
  const password = process.env.ADMIN_PASSWORD;
  if (!login || !password) {
    console.warn("ADMIN_LOGIN / ADMIN_PASSWORD не заданы — войти как админ не получится");
    return;
  }
  const name = process.env.ADMIN_NAME?.trim() || process.env.ADMIN_LOGIN!.trim();

  const [existing] = await db.query<{ id: string; name: string; role: string; password_hash: string }>(
    "SELECT id, name, role, password_hash FROM users WHERE login = $1",
    [login],
  );
  if (!existing) {
    await db.query(
      "INSERT INTO users (login, name, password_hash, role) VALUES ($1, $2, $3, 'admin') ON CONFLICT (login) DO NOTHING",
      [login, name, await hashPassword(password)],
    );
    return;
  }

  const samePassword = await verifyPassword(password, existing.password_hash);
  if (samePassword && existing.role === "admin" && existing.name === name) return;

  // Обновляем имя (ADMIN_NAME), роль и пароль — всё берётся из переменных окружения
  await db.query("UPDATE users SET name = $1, role = 'admin', password_hash = $2 WHERE id = $3::uuid", [
    name,
    samePassword ? existing.password_hash : await hashPassword(password),
    existing.id,
  ]);
  // Пароль поменяли (например, старый кто-то узнал) — старые входы больше не действуют
  if (!samePassword) await db.query("DELETE FROM sessions WHERE user_id = $1::uuid", [existing.id]);
}
